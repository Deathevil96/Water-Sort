using System;
using System.IO;
using System.Text;
using PaintSort.Core;
using UnityEditor;
using UnityEngine;

namespace PaintSort.EditorTools
{
    public static class LevelTools
    {
        const string CatalogPath = "Assets/Resources/Levels/levels.txt";
        const string ReportDir = "Reports";

        /// <summary>Size of the shipped catalog. Generation is deterministic, so raising this only appends new levels.</summary>
        public const int CatalogSize = 5000;

        [MenuItem("Paint Sort/Generate Level Catalog (5000)")]
        public static void GenerateCatalog() => Generate(CatalogSize);

        // Command line: Unity -batchmode -executeMethod PaintSort.EditorTools.LevelTools.GenerateBatch -quit
        public static void GenerateBatch()
        {
            try { Generate(CatalogSize); } catch (Exception e) { Debug.LogError(e); EditorApplication.Exit(1); return; }
            EditorApplication.Exit(0);
        }

        public static void Generate(int count)
        {
            var sb = new StringBuilder();
            sb.Append("# Paint Sort level catalog v1: id;difficulty;seed;pots;witness  (generated by LevelTools, do not hand-edit)\n");
            var sw = System.Diagnostics.Stopwatch.StartNew();
            for (int id = 1; id <= count; id++)
            {
                var r = LevelGenerator.Generate(id);
                sb.Append(LevelCodec.Encode(r.Level)).Append('\n');
                if (id % 50 == 0)
                {
                    Debug.Log("[LEVEL] generated " + id + "/" + count + " in " + sw.Elapsed.TotalSeconds.ToString("F0") + "s");
                    if (!Application.isBatchMode) EditorUtility.DisplayProgressBar("Generating levels", id + "/" + count, id / (float)count);
                }
            }
            if (!Application.isBatchMode) EditorUtility.ClearProgressBar();
            Directory.CreateDirectory(Path.GetDirectoryName(CatalogPath));
            File.WriteAllText(CatalogPath, sb.ToString());
            AssetDatabase.Refresh();
            Debug.Log("[LEVEL] catalog written: " + count + " levels in " + sw.Elapsed.TotalSeconds.ToString("F0") + "s");
        }

        [MenuItem("Paint Sort/Test All Levels (witness + special mechanics)")]
        public static void AuditMenu() => Audit(false);
        [MenuItem("Paint Sort/Test All Levels (+ solver)")]
        public static void AuditSolverMenu() => Audit(true);

        public static void AuditBatch() { var rep = Audit(false); EditorApplication.Exit(rep.Pass ? 0 : 2); }
        public static void AuditSolverBatch() { var rep = Audit(true); EditorApplication.Exit(rep.Pass ? 0 : 2); }

        public static AuditReport Audit(bool solver)
        {
            var cat = LevelCatalog.Parse(File.ReadAllText(CatalogPath));
            var rep = LevelAudit.Run(cat.All(), solver, 60000);
            Directory.CreateDirectory(ReportDir);
            File.WriteAllText(Path.Combine(ReportDir, "level_audit.csv"), rep.ToCsv());
            File.WriteAllText(Path.Combine(ReportDir, "level_audit.json"), rep.ToJson());
            Debug.Log("[LEVEL] " + rep.Summary() + (rep.FailedIds.Count > 0 ? "\nFailed: " + string.Join(",", rep.FailedIds) : ""));
            return rep;
        }
    }
}
